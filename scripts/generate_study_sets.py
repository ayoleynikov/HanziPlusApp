def write_json(filename: str, words: list[dict]) -> None:
    path = DATA_DIR / filename
    with path.open("w", encoding="utf-8") as f:
        json.dump(words, f, ensure_ascii=False, indent=2)
        f.write("\n")


def print_counts(filename: str, words: list[dict]) -> None:
    counts = Counter(w["section"] for w in words)
    print(f"\n{filename} ({len(words)} words total):")
    for section, count in counts.items():
        print(f"  {section}: {count}")


