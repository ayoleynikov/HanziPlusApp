# (hanzi, pinyin, english, (ex_h, ex_p, ex_e), (ex_h, ex_p, ex_e))
WordTuple = tuple[str, str, str, tuple[str, str, str], tuple[str, str, str]]


def w(section: str, hanzi: str, pinyin: str, english: str,
      ex1: tuple[str, str, str], ex2: tuple[str, str, str]) -> dict:
    """Build one vocabulary entry with two example sentences."""
    def example(h: str, p: str, e: str) -> dict:
        return {"hanzi": h, "pinyin": p, "english": e}

    return {
        "section": section,
        "hanzi": hanzi,
        "pinyin": pinyin,
        "english": english,
        "examples": [example(*ex1), example(*ex2)],
    }


def section_words(section: str, words: list[WordTuple]) -> list[dict]:
    return [w(section, *word) for word in words]


def load_existing_travel() -> dict[str, dict]:
    if not TRAVEL_PATH.exists():
        return {}
    with TRAVEL_PATH.open(encoding="utf-8") as f:
        items = json.load(f)
    return {item["hanzi"]: item for item in items}


